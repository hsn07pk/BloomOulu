const localisePlant = (p, lang) => {
  if (lang === "EN") return p;
  const local = { ...p };
  if (PLANT_STORIES[lang]?.[p.id]) local.story = PLANT_STORIES[lang][p.id];
  if (PLANT_NAMES_LOCAL[lang]?.[p.id]) local.localName = PLANT_NAMES_LOCAL[lang][p.id];
  // Also translate rarity label
  local.rarityLabel = translate(p.rarityLabel, lang);
  return local;
};

const localiseTier = (tier, lang) => {
  if (lang === "EN") return tier;
  const tc = TIER_COPY[lang]?.[tier.name];
  if (!tc) return tier;
  return { ...tier, name: tc.name, blurb: tc.blurb, perks: tc.perks, tag: TAGS_LOCAL[lang]?.[tier.tag] || tier.tag };
};

